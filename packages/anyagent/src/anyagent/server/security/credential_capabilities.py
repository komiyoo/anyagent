from __future__ import annotations

from anyagent.protocol.credential_vault import CredentialBackendCapability, CredentialBackendCapabilityMatrix


def build_credential_backend_capability_matrix() -> CredentialBackendCapabilityMatrix:
    """Return the Core credential backend capability matrix.

    The matrix is deliberately static: it documents selectable backend modes
    without reading deployment env vars or credential values.
    """

    return CredentialBackendCapabilityMatrix(
        resolver_modes=[
            CredentialBackendCapability(
                mode="none",
                display_name="No external resolver",
                kind="resolver",
                description="Disables external MCP credential resolution; Core may still use its in-process Admin API store.",
                supports_resolve=False,
                supports_set=False,
                supports_delete=False,
                supports_list_refs=False,
                read_only=True,
                default_for=["anyagent serve"],
                source="anyagent.server.security.mcp_credentials.build_mcp_credential_resolver",
            ),
            CredentialBackendCapability(
                mode="env",
                display_name="Environment resolver",
                kind="resolver",
                description="Resolves AuthRef values from environment variables such as CREDENTIAL__<CREDENTIAL_ID>.",
                supports_resolve=True,
                supports_set=False,
                supports_delete=False,
                supports_list_refs=False,
                read_only=True,
                source="anyagent.mcp.auth.EnvCredentialResolver",
            ),
            CredentialBackendCapability(
                mode="file",
                display_name="File resolver",
                kind="resolver",
                description="Resolves AuthRef values from JSON credential files under MCP_CREDENTIAL_STORE_FILE_ROOT.",
                supports_resolve=True,
                supports_set=False,
                supports_delete=False,
                supports_list_refs=False,
                read_only=True,
                requires_env=["MCP_CREDENTIAL_STORE_FILE_ROOT"],
                source="anyagent.mcp.auth.FileCredentialResolver",
            ),
            CredentialBackendCapability(
                mode="infisical",
                display_name="Infisical resolver",
                kind="resolver",
                description="Resolves AuthRef values from Infisical using universal auth.",
                supports_resolve=True,
                supports_set=False,
                supports_delete=False,
                supports_list_refs=False,
                read_only=True,
                requires_extras=["infisical"],
                requires_env=[
                    "INFISICAL_UNIVERSAL_AUTH_CLIENT_ID",
                    "INFISICAL_UNIVERSAL_AUTH_CLIENT_SECRET",
                    "INFISICAL_TOKEN",
                    "INFISICAL_PROJECT_ID",
                    "INFISICAL_ENVIRONMENT",
                ],
                source="anyagent.server.security.mcp_credentials.InfisicalCredentialResolver",
            ),
        ],
        admin_store_modes=[
            CredentialBackendCapability(
                mode="memory",
                display_name="In-process Admin API store",
                kind="admin_store",
                description="Default write-only Admin API credential store for local Core server use; not durable across restart.",
                supports_resolve=True,
                supports_set=True,
                supports_delete=True,
                supports_list_refs=True,
                read_only=False,
                default_for=["anyagent serve"],
                source="anyagent.server.security.credential_store.InMemoryCredentialStore",
            ),
            CredentialBackendCapability(
                mode="env-write",
                display_name="Environment-backed write store",
                kind="admin_store",
                description="Stores Admin API writes in process memory and can resolve registered refs through metadata env_var_name or CREDENTIAL__<CREDENTIAL_ID>.",
                supports_resolve=True,
                supports_set=True,
                supports_delete=True,
                supports_list_refs=True,
                read_only=False,
                source="anyagent.server.security.credential_backends.EnvBackend",
            ),
            CredentialBackendCapability(
                mode="file-write",
                display_name="File credential store",
                kind="admin_store",
                description="Stores Admin API credential refs as chmod 600 JSON files under MCP_CREDENTIAL_STORE_FILE_ROOT.",
                supports_resolve=True,
                supports_set=True,
                supports_delete=True,
                supports_list_refs=True,
                read_only=False,
                requires_env=["MCP_CREDENTIAL_STORE_FILE_ROOT"],
                source="anyagent.server.security.credential_backends.FileBackend",
            ),
            CredentialBackendCapability(
                mode="infisical-write",
                display_name="Infisical credential store",
                kind="admin_store",
                description="Lists and resolves Infisical credential refs; write and delete are intentionally unavailable until a safe mutation contract lands.",
                supports_resolve=True,
                supports_set=False,
                supports_delete=False,
                supports_list_refs=True,
                read_only=True,
                requires_extras=["infisical"],
                requires_env=[
                    "INFISICAL_UNIVERSAL_AUTH_CLIENT_ID",
                    "INFISICAL_UNIVERSAL_AUTH_CLIENT_SECRET",
                    "INFISICAL_TOKEN",
                    "INFISICAL_PROJECT_ID",
                    "INFISICAL_ENVIRONMENT",
                ],
                source="anyagent.server.security.credential_backends.InfisicalBackend",
            ),
            CredentialBackendCapability(
                mode="db",
                display_name="Database credential store",
                kind="admin_store",
                status="preview",
                description="Durable PostgreSQL credential store using pgcrypto encrypted value columns and persistent credential_audit rows.",
                supports_resolve=True,
                supports_set=True,
                supports_delete=True,
                supports_list_refs=True,
                read_only=False,
                requires_extras=["postgres"],
                requires_env=["CREDENTIAL_ENCRYPTION_KEY", "POSTGRES_DSN or CREDENTIAL_POSTGRES_DSN"],
                source="anyagent.server.security.credential_backends.DatabaseBackend",
            ),
            CredentialBackendCapability(
                mode="vault",
                display_name="Vault credential store",
                kind="admin_store",
                status="preview",
                description="HashiCorp Vault KV v2 credential store with explicit mutation and lifecycle metadata.",
                supports_resolve=True,
                supports_set=True,
                supports_delete=True,
                supports_list_refs=True,
                read_only=False,
                requires_env=["VAULT_ADDR", "VAULT_TOKEN"],
                source="anyagent.server.security.credential_backends.VaultBackend",
            ),
        ],
    )
